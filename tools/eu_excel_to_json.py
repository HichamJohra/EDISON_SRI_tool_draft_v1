"""Convert an official EU SRI calculation sheet (Excel, v4.5) into the app's JSON files.

Usage (openpyxl is not an app dependency, uv adds it for this run only):
    uv run --with openpyxl python tools/eu_excel_to_json.py <assessment.xlsx> <assessment.json> \
        [--name "Building name"] [--catalogue data/sri_catalogue_v4_5.json]

Writes:
- the assessment: building, method, results as computed by the sheet, the weightings it applied, and for every
  service the assessed level, whether it counts in the maximum score, and its maximum impact scores;
- optionally the service catalogue (all services, every functionality level with its 7 impact scores and the
  reference standard), which is the same for every assessment made with this sheet version.

Reads cached values: open and save the file in Excel once if it was generated by another program.
Column positions are those of the 'Calculation' sheet in version 4.5.
"""
import argparse
import json
import math
import re
import warnings
from pathlib import Path

import openpyxl

IMPACTS = ["Energy efficiency", "Energy flexibility and storage", "Comfort", "Convenience",
           "Health, well-being and accessibility", "Maintenance and fault prediction", "Information to occupants"]
DOMAINS = ["Heating", "Domestic hot water", "Cooling", "Ventilation", "Lighting", "Dynamic building envelope",
           "Electricity", "Electric vehicle charging", "Monitoring and control"]
DOMAIN_TABS = {"H": "Heating", "DHW": "Domestic hot water", "C": "Cooling", "V": "Ventilation", "L": "Lighting",
               "DE": "Dynamic building envelope", "E": "Electricity", "EV": "Electric vehicle charging",
               "MC": "Monitoring and control"}
KEY_FUNCTIONALITIES = ["Key functionality 1 - building", "Key functionality 2 - user", "Key functionality 3 - grid"]
CODE_RE = re.compile(r"^[A-Z]+-\d+[a-z]?$")

# 'Calculation' sheet, v4.5 (0-based column indexes)
C_DOMAIN, C_CODE, C_GROUP, C_SERVICE, C_TRIAGE, C_APPLICABLE, C_LEVEL = 0, 1, 2, 3, 6, 8, 9
C_IN_METHOD, C_IN_MAX, C_MAX_LEVEL = 19, 25, 28
C_DOMAIN_WEIGHTS, C_MAX_SCORES, C_IMPACT_WEIGHTS = 50, 93, 83  # 7 columns each


def _num(v):
    """Float or None (Excel errors such as #DIV/0! mean 'not applicable')."""
    if isinstance(v, (int, float)) and not (isinstance(v, float) and math.isnan(v)):
        return float(v)
    return None


def _label_value(ws, labels):
    """Map 'label in a cell' -> value in the next non-empty cell of the same row (first occurrence)."""
    out = {}
    for row in ws.iter_rows(values_only=True):
        cells = [c for c in row if c not in (None, "")]
        for i, c in enumerate(cells[:-1]):
            if isinstance(c, str) and c.strip() in labels and c.strip() not in out:
                out[c.strip()] = cells[i + 1]
    return out


def read_catalogue(wb) -> dict:
    """All services of the domain tabs: levels with descriptions and the 7 ordinal impact scores."""
    cat = {}
    for tab, domain in DOMAIN_TABS.items():
        cur = None
        for row in wb[tab].iter_rows(values_only=True):
            r = list(row) + [None] * 20
            if isinstance(r[2], str) and CODE_RE.match(r[2]):
                cur = {"code": r[2], "domain": domain, "group": r[6], "service": r[3], "standard": None, "levels": []}
                cat[r[2]] = cur
            elif cur is not None and isinstance(r[2], str) and r[2].startswith("level "):
                level = int(r[2].split()[1])
                if cur["levels"] and level <= cur["levels"][-1]["level"]:
                    cur = None  # a new block without service code (spare template rows, '#REF!'): stop here
                    continue
                if r[3] in (None, 0, "0", "") or str(r[3]).startswith("#"):
                    continue  # level not defined for this service (or an Excel error)
                cur["levels"].append({"level": level, "description": str(r[3]).strip(),
                                      "impacts": [r[4 + k] if isinstance(r[4 + k], (int, float)) else 0
                                                  for k in range(len(IMPACTS))]})
            elif cur is not None and r[3] == "Standard?" and isinstance(r[4], str) and r[4].strip():
                cur["standard"] = r[4].strip()
    return cat


def convert(path: Path, name: str | None = None, source_file: str | None = None) -> tuple[dict, dict]:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # openpyxl: unsupported data-validation extensions
        wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
    catalogue = read_catalogue(wb)

    info = _label_value(wb["Building Information"], {
        "Building type", "Building usage", "Location", "Climate zone:", "Total useful floor area of the building",
        "Year of construction", "Building state", "Preferred weightings", "Preferred services catalogue",
        "Year", "Month", "Day"})
    info_rows = list(wb["Building Information"].iter_rows(values_only=True))
    description = next((next((v for v in r[i + 1:] if v not in (None, "")), None)
                        for r in info_rows for i, c in enumerate(r[:-1])
                        if isinstance(c, str) and c.startswith("Please provide a brief description")), None)

    res_rows = [list(r) for r in wb["Results"].iter_rows(values_only=True)]

    def right_of(label):
        for r in res_rows:
            for j, c in enumerate(r):
                if isinstance(c, str) and c.strip() == label:
                    return next((v for v in r[j + 1:] if v not in (None, "")), None)
        return None

    start = next(i for i, r in enumerate(res_rows) if "DOMAIN SCORES" in r)
    domains, detail = {}, {}
    for r in res_rows[start + 1:start + 12]:
        cells = [c for c in r if c is not None]
        if cells and cells[0] in DOMAINS and len(cells) >= 10:
            domains[cells[0]] = _num(cells[1])
            detail[cells[0]] = dict(zip(IMPACTS, [_num(v) for v in cells[3:10]]))

    calc_rows = list(wb["Calculation"].iter_rows(values_only=True))
    impact_weights = [_num(v) for v in calc_rows[4][C_IMPACT_WEIGHTS:C_IMPACT_WEIGHTS + 7]]  # row 5
    services, domain_weights = [], {}
    for r in calc_rows[5:]:
        if not r or not isinstance(r[C_CODE], str) or not CODE_RE.match(r[C_CODE]) or r[C_IN_METHOD] != 1:
            continue
        code = r[C_CODE]
        domain = catalogue[code]["domain"] if code in catalogue else r[C_DOMAIN]
        domain_weights.setdefault(domain, [_num(v) or 0.0 for v in r[C_DOMAIN_WEIGHTS:C_DOMAIN_WEIGHTS + 7]])
        level = int(r[C_LEVEL]) if isinstance(r[C_LEVEL], (int, float)) else 0
        levels = catalogue.get(code, {}).get("levels", [])
        services.append({
            "domain": domain, "code": code, "group": r[C_GROUP], "service": r[C_SERVICE],
            "applicable": r[C_APPLICABLE] == 1, "triage": r[C_TRIAGE] == 1,
            "in_max_score": r[C_IN_MAX] == 1,
            "level": level, "max_level": max((lv["level"] for lv in levels), default=0),
            "max_level_possible": int(r[C_MAX_LEVEL]) if isinstance(r[C_MAX_LEVEL], (int, float)) else None,
            "level_description": next((lv["description"] for lv in levels if lv["level"] == level), None),
            # Maximum ordinal impact scores as used by the sheet (also for services outside the maximum score)
            "max_impacts": [_num(v) or 0.0 for v in r[C_MAX_SCORES:C_MAX_SCORES + 7]],
        })

    date = None
    if all(isinstance(info.get(k), (int, float)) for k in ("Year", "Month", "Day")):
        date = f"{int(info['Year']):04d}-{int(info['Month']):02d}-{int(info['Day']):02d}"
    assessment = {
        "format": "edison-sri-assessment/0.2",
        "source": {"tool": "EU SRI calculation sheet", "version": "4.5", "file": source_file or path.name},
        "building": {
            "name": name or path.stem, "description": description,
            "type": info.get("Building type"), "usage": info.get("Building usage"),
            "location": info.get("Location"), "climate_zone": info.get("Climate zone:"),
            "floor_area_class": info.get("Total useful floor area of the building"),
            "construction_year": info.get("Year of construction"), "state": info.get("Building state"),
        },
        "method": {"catalogue": info.get("Preferred services catalogue"), "weightings": info.get("Preferred weightings")},
        "assessment_date": date,
        "weights": {"impact_criteria": impact_weights, "domains": domain_weights},
        "results": {"total": _num(right_of("TOTAL SRI SCORE")), "class": right_of("SRI CLASS"),
                    "impact_criteria": {k: _num(right_of(k)) for k in IMPACTS},
                    "key_functionalities": {k: _num(right_of(k)) for k in KEY_FUNCTIONALITIES},
                    "domains": domains, "domain_impact": detail},
        "services": services,
    }
    cat_out = {"format": "edison-sri-catalogue/0.1", "source": "EU SRI calculation sheet v4.5",
               "impact_criteria": IMPACTS, "domains": DOMAINS, "services": list(catalogue.values())}
    return assessment, cat_out


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("xlsx", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--name")
    ap.add_argument("--source-file", help="file name to record (default: the input file name)")
    ap.add_argument("--catalogue", type=Path, help="also write the service catalogue to this JSON file")
    a = ap.parse_args()
    data, cat = convert(a.xlsx, a.name, a.source_file)
    a.out.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{a.out}: SRI {data['results']['total']:.1%}, {len(data['services'])} services")
    if a.catalogue:
        a.catalogue.write_text(json.dumps(cat, indent=1, ensure_ascii=False), encoding="utf-8")
        print(f"{a.catalogue}: {len(cat['services'])} services")
